    fun fallback(type: Int): String = if (type == Type.INCOME) "其他收入" else "其他"

    /**
     * @param text 商户名 + 备注 + 原始通知/短信文本
     * @return 分类名 to 是否由规则命中
     */
    fun categorize(text: String, type: Int, userRules: List<Rule>): Pair<String, Boolean> {
        val t = text.lowercase().trim()
        if (t.isEmpty()) return fallback(type) to false

        val candidates = userRules
            .filter { it.enabled && it.type == type && it.keyword.isNotBlank() }
            .sortedByDescending { it.keyword.length }

        for (r in candidates) {
            if (t.contains(r.keyword.lowercase())) return r.category to true
        }

        for (k in builtin) {
            if (k.type == type && t.contains(k.kw)) return k.cat to true
        }

        return fallback(type) to false
    }
